#!/usr/bin/env python3
"""Regenerates OracleCharts.kt and OracleGoldSizes.kt from the oracle data.

The .mmd files are the single source of truth; this embeds them in the
sample apps so oracle mode can render them by id on device. The golden
content sizes are embedded too: oracle mode picks its render density so the
diagram's content comes out at the golden's pixel size, and compare.py can
then compare the two 1:1.

Run with oracle/tools/.venv/bin/python (needs Pillow to measure goldens).
"""
import pathlib
import sys

from PIL import Image, ImageChops

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
CHARTS = ROOT / "oracle" / "charts"
GOLDENS = ROOT / "oracle" / "goldens"
SRC = ROOT / "sample-shared" / "src" / "commonMain" / "kotlin" / "dev" / "maradona" / "sample"
OUT = SRC / "OracleCharts.kt"
OUT_SIZES = SRC / "OracleGoldSizes.kt"
BG_TOLERANCE = 28


def golden_content_size(path: pathlib.Path) -> tuple[int, int]:
    """Golden's ink bounding box - the size oracle mode has to reproduce."""
    img = Image.open(path).convert("RGB")
    w, h = img.size
    pts = [img.getpixel(p) for p in [(2, 2), (w - 3, 2), (2, h - 3), (w - 3, h - 3)]]
    bg = tuple(sorted(c[i] for c in pts)[1] for i in range(3))
    diff = ImageChops.difference(img, Image.new("RGB", img.size, bg)).convert("L")
    bbox = diff.point(lambda v: 255 if v > BG_TOLERANCE else 0).getbbox()
    if bbox is None:
        raise SystemExit(f"error: {path.name} has no content")
    return bbox[2] - bbox[0], bbox[3] - bbox[1]


def main() -> int:
    entries = []
    sizes = []
    for mmd in sorted(CHARTS.glob("*.mmd")):
        text = mmd.read_text().strip("\n")
        if '"""' in text or "$" in text:
            print(f"error: {mmd.name} contains a sequence illegal in Kotlin raw strings", file=sys.stderr)
            return 1
        indented = "\n".join("        " + line for line in text.split("\n"))
        entries.append(f'        "{mmd.stem}" to """\n{indented}\n        """.trimIndent(),')
        w, h = golden_content_size(GOLDENS / f"{mmd.stem}.png")
        sizes.append(f'        "{mmd.stem}" to IntSize({w}, {h}),')
    body = "\n".join(entries)
    OUT.write_text(
        "package dev.maradona.sample\n"
        "\n"
        "// GENERATED by oracle/tools/sync_charts.py - do not edit by hand.\n"
        "/** Oracle chart sources, keyed by chart id (= oracle/charts file name). */\n"
        "object OracleCharts {\n"
        "    val all: Map<String, String> = mapOf(\n"
        f"{body}\n"
        "    )\n"
        "}\n"
    )
    size_body = "\n".join(sizes)
    OUT_SIZES.write_text(
        "package dev.maradona.sample\n"
        "\n"
        "import androidx.compose.ui.unit.IntSize\n"
        "\n"
        "// GENERATED by oracle/tools/sync_charts.py - do not edit by hand.\n"
        "/**\n"
        " * Content (ink bounding box) size of each mermaid golden, in pixels.\n"
        " *\n"
        " * Oracle mode chooses its render density so the diagram's content comes out\n"
        " * at this size, which lets the oracle compare renders 1:1 instead of\n"
        " * rescaling one side to the other.\n"
        " */\n"
        "object OracleGoldSizes {\n"
        "    val content: Map<String, IntSize> = mapOf(\n"
        f"{size_body}\n"
        "    )\n"
        "}\n"
    )
    print(f"wrote {OUT} ({len(entries)} charts)")
    print(f"wrote {OUT_SIZES}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
